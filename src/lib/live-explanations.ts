/** An observed difference, not proof of an internal hardware cause. */
export function largestStartupGap(gl: LiveLane, gpu: LiveLane) {
  if (gl.state !== 'complete' || gpu.state !== 'complete' || gl.run !== gpu.run || gl.commonStart !== gpu.commonStart) return null;
  const fields: [keyof LiveStats, string][] = [
    ['moduleMs', 'Зураг зурах код бэлэн болох хүлээлт'], ['deviceMs', 'GPU-тэй ажиллах орчин бэлдэх'],
    ['copyMs', 'Өөрийн өгөгдлийн хувийг бэлдэх'], ['setupMs', 'Шэйдер ба зурах тохиргоо бэлдэх'],
  ];
  return fields.flatMap(([key, label]) => {
    const a = gl.metrics[key], b = gpu.metrics[key];
    return typeof a === 'number' && typeof b === 'number' ? [{ label, gapMs: b - a }] : [];
  }).sort((a, b) => Math.abs(b.gapMs) - Math.abs(a.gapMs))[0] ?? null;
}
